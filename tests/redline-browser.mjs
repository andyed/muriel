// Local full Chrome acceptance check. Usage:
// PLAYWRIGHT_MODULE=/path/to/playwright node tests/redline-browser.mjs review.html /tmp/redline-proof
// Full Chrome stays on cylon; pure Python tests run on BIGFU.
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {mkdir} from 'node:fs/promises';
import {resolve, join} from 'node:path';
import {pathToFileURL} from 'node:url';
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.PLAYWRIGHT_MODULE || 'playwright');
if(!process.argv[2])throw new Error('Pass the generated three-revision jury review HTML');
const url=pathToFileURL(resolve(process.argv[2])).href;
const out=resolve(process.argv[3] || '/tmp/muriel-redline-proof');
await mkdir(out,{recursive:true});
const browser=await chromium.launch({channel:'chrome',headless:true});
const errors=[];
try {
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(url);await page.locator('#capture').evaluate(img=>img.decode());
  assert.equal(await page.locator('#frame-title').innerText(),'First draft');
  assert.equal(await page.locator('#prev').isDisabled(),true);
  await page.getByRole('button',{name:'2 Axis and grid endpoints',exact:true}).click();
  assert.match(await page.locator('.measure').innerText(),/6 capture px/);
  await page.locator('#next').click();await page.locator('#next').click();
  assert.equal(await page.locator('#next').isDisabled(),true);
  await page.getByRole('button',{name:'4 Quarter label and reporting period',exact:true}).click();
  assert.equal(await page.locator('.status.unverified').count(),1);
  await page.locator('#compare').click();
  assert.match(await page.locator('#frame-title').innerText(),/^Original/);
  await page.locator('#compare').click();
  assert.match(await page.locator('#findings button[aria-pressed=true]').innerText(),/Quarter label/);
  await page.locator('#revision').focus();await page.keyboard.press('Home');
  assert.equal(await page.locator('#frame-title').innerText(),'First draft');
  await page.keyboard.press('End');
  assert.equal(await page.locator('#frame-title').innerText(),'Second revision');
  await page.locator('#scale').click();
  const pixels=await page.evaluate(()=>({canvas:document.querySelector('#canvas').getBoundingClientRect().width,image:document.querySelector('#capture').getBoundingClientRect().width,viewBox:document.querySelector('#overlay').getAttribute('viewBox')}));
  assert.equal(pixels.canvas,1200);assert.equal(pixels.image,1200);assert.equal(pixels.viewBox,'0 0 1200 747');
  await page.locator('#annotations').uncheck();assert.equal(await page.locator('#overlay').isVisible(),false);
  await page.locator('#annotations').check();await page.locator('#scale').click();
  await page.locator('#play').click();
  assert.equal(await page.locator('#play').getAttribute('aria-pressed'),'true');
  await page.locator('#next').click();
  assert.equal(await page.locator('#play').getAttribute('aria-pressed'),'false');
  const manual=await page.locator('#revision').inputValue();
  await page.waitForTimeout(2600);assert.equal(await page.locator('#revision').inputValue(),manual);
  await page.locator('#next').click();
  await page.screenshot({path:join(out,'desktop.png'),fullPage:true});
  await page.emulateMedia({reducedMotion:'reduce'});
  assert.equal(await page.locator('#overlay').evaluate(n=>getComputedStyle(n).animationName),'none');
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth),390);
  await page.screenshot({path:join(out,'mobile.png'),fullPage:true});
  await page.locator('#scale').click();
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth),390);
  await page.locator('#viewport').focus();await page.keyboard.press('ArrowRight');
  await page.waitForTimeout(180);
  assert.ok(await page.locator('#viewport').evaluate(n=>n.scrollLeft>0));
  await page.emulateMedia({media:'print'});
  assert.equal(await page.locator('.static').isVisible(),true);
  assert.equal(await page.locator('#app').isVisible(),false);
  const nojs=await browser.newContext({javaScriptEnabled:false,viewport:{width:390,height:844}});
  const staticPage=await nojs.newPage();await staticPage.goto(url);
  assert.equal(await staticPage.locator('.static section').count(),3);
  assert.equal(await staticPage.locator('.static img').count(),3);
  assert.equal(await staticPage.locator('#app').isVisible(),false);
  assert.equal(await staticPage.evaluate(()=>document.documentElement.scrollWidth),390);
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({passed:true,checks:['revision boundaries','keyboard scrubber','original return and finding selection','pixel registration','redline visibility','manual interruption','reduced motion','mobile overflow and pixel scrolling','print','no-JS'],screenshots:out},null,2));
} finally {await browser.close();}
